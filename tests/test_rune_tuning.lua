dofile("tests/wow_stubs.lua")
dofile("tests/harness.lua")
WoW.version = "dev"
local GMM = loadAddon()
GMM._test.slash("runes style glowing")
GMM._test.slash("runes motion orbit")
GMM._test.slash("runes fog on")
GMM._test.slash("runes on")
local frame, animation, layer = GMM.Ring._test.runes()
local base = GMM.Ring._test.etchedBase()
local light = GMM.Ring._test.bloom():GetRegions()
local fog, fogAnimation = GMM.Ring._test.fog()
local mist = fog:GetRegions()
local mistAlpha, plays = mist._vertex[4], animation._plays
GMM._test.slash("runes intensity 50")
near(light._vertex[4], 0.35, "intensity halves bloom")
near(layer.core._vertex[4], 0.25, "intensity halves glowing core")
near(layer.glow._vertex[4], 0.2, "intensity halves halo")
eq(mist._vertex[4], mistAlpha, "intensity leaves vapor alone")
near(base._vertex[4], 0.65, "intensity leaves stationary engraving readable")
eq(animation._plays, plays, "intensity preserves motion")
GMM.Settings.SetTheme("smoked")
near(light._vertex[4], 0.35 * (0.14 / 0.18), "theme wash and intensity combine")
GMM.Settings.SetTheme("clear")
GMM._test.slash("runes intensity 0")
eq(light._vertex[4], 0, "zero removes bloom")
near(base._vertex[4], 0.65, "zero glow retains stationary engraving")
GMM._test.slash("runes style etched")
near(layer.core._vertex[4], 0.65, "etched ignores glow intensity")
GMM._test.slash("runes speed 200")
eq(layer.rotation._duration / animation:GetAnimationSpeedMultiplier(), 15, "double speed halves effective period")
check(layer.frame ~= nil, "one moving layer over stationary engraving")
local fogPlays = fogAnimation._plays
GMM._test.slash("runes speed 25")
eq(layer.rotation._duration / animation:GetAnimationSpeedMultiplier(), 120, "quarter speed effective period")
eq(fogAnimation._plays, fogPlays, "speed leaves vapor motion alone")
GMM._test.slash("runes motion sway")
plays = animation._plays
GMM._test.slash("runes speed 150")
eq(layer.rotation._duration, 2, "orbit speed leaves sway timing alone")
eq(animation._plays, plays, "speed does not restart sway")
for _, pair in ipairs({ {"runeIntensity", -1}, {"runeIntensity", 101}, {"runeSpeed", 0},
    {"runeSpeed", 201}, {"runeSpeed", "fast"}, {"runeSpeed", 0/0}, {"other", 50} }) do
    check(not GMM.Settings.SetRuneTuning(pair[1], pair[2]), "reject invalid tuning")
end
GMM.Options._test.panel:Show()
GMM.Options._test.intensity:SetValue(40)
GMM.Options._test.speed:SetValue(75)
eq(GMM.db.runeIntensity, 40, "intensity slider uses settings")
eq(GMM.db.runeSpeed, 75, "speed slider uses settings")
local saved = GlassMiniMapDB
GMM = loadAddon({ db = saved })
eq(GMM.db.runeIntensity, 40, "intensity survives reload")
eq(GMM.db.runeSpeed, 75, "speed survives reload")
GMM._test.slash("runes motion orbit")
local _, _, restored = GMM.Ring._test.runes()
eq(restored.rotation._duration / restored.animation:GetAnimationSpeedMultiplier(), 40, "restored speed applies")
GMM.Settings.SetRuneTuning("runeIntensity", 100)
GMM.Settings.SetRuneTuning("runeSpeed", 100)
eq(rawget(GlassMiniMapDB, "runeIntensity"), nil, "default intensity is not stored")
eq(rawget(GlassMiniMapDB, "runeSpeed"), nil, "default speed is not stored")
GMM = loadAddon({ db = { runeIntensity = "bad", runeSpeed = math.huge } })
eq(GMM.db.runeIntensity, 100, "invalid saved intensity repaired")
eq(GMM.db.runeSpeed, 100, "invalid saved speed repaired")
eq(next(GMM.failures), nil, "no tuning failures")
done("test_rune_tuning")
