eq(y, 18, "fog extends above ring")
corner, anchor, relative, x, y = fog:GetPoint(2)
eq(x, 18, "fog extends outside right edge")
eq(y, -18, "fog extends below ring")
local drift = fogAnimation:GetAnimations()
