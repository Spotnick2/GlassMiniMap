-- Development preview: lifecycle and native animation configuration.
dofile("tests/wow_stubs.lua")
dofile("tests/harness.lua")

WoW.version = "dev"
local GMM = loadAddon()
GMM.Settings.SetRunePreviewOption("style", "etched")
local frame, animation, layers = GMM.Ring._test.runes()
local bloom = GMM.Ring._test.bloom()
local base = GMM.Ring._test.etchedBase()
eq(base:GetParent(), frame, "engraving belongs to unanimated wrapper")
eq(#(frame._anims or {}), 0, "wrapper has no animations")
eq(base._file, GMM.MEDIA .. "ring_runes", "stationary engraving uses rune artwork")
eq(base._blendMode, "BLEND", "stationary engraving is not additive")
eq(bloom:GetParent(), layers[1].frame, "rim bloom shares primary rune motion and visibility")
local _, bloomAnchor = bloom:GetPoint(1)
eq(bloomAnchor, layers[1].frame, "rim bloom anchors to its animated parent")
check(not bloom:IsShown(), "etched starts without rim bloom")
check(not bloom:IsMouseEnabled(), "rim bloom does not intercept clicks")
check(frame ~= nil, "dev build creates the preview")
check(not frame:IsShown() and not animation:IsPlaying(), "off on login")
eq(frame:GetParent(), GMM.Ring.Container(), "inherits Edit Mode scaling")
eq(frame:GetFrameLevel(), Minimap:GetFrameLevel() + 3, "below tab and discs")
check(not frame:IsMouseEnabled(), "does not intercept clicks")
eq(frame:GetScript("OnUpdate"), nil, "no rune update loop")
local texture = layers[1].core
eq(texture._file, GMM.MEDIA .. "ring_runes_moving", "moving layer uses sparse artwork")
local rotation = animation:GetAnimations()
eq(rotation._type, "Rotation", "native rotation")
eq(rotation._order, 1, "explicit animation order")
eq(rotation._degrees, 4, "four degrees per leg")
eq(rotation._duration, 2, "two seconds per leg")
eq(rotation._smoothing, "IN_OUT", "eased endpoints")
eq(rotation._origin, "CENTER", "turns around centre")
eq(animation._looping, "REPEAT", "repeat explicit out-and-back sequence")
local timers = #WoW.timers
GMM._test.slash("runes on")
check(frame:IsVisible() and animation:IsPlaying(), "command enables preview")
animation._progress = 0.375
GMM._test.slash("runes status")
check(WoW.chat[#WoW.chat]:find("enabled=true, visible=true, playing=true, progress=0.375", 1, true),
    "status reports live animation state and progress")
eq(#WoW.timers, timers, "preview adds no timers")
local plays = animation._plays
GMM._test.slash("runes on")
GMM.Theme.Refresh()
eq(animation._plays, plays, "repeated enable and repaint preserve phase")
WoW.finishAnimations()
check(animation:IsPlaying(), "loop survives finite animation completion")
GMM._test.slash("runes maybe")
check(animation:IsPlaying(), "invalid argument leaves preview alone")

Minimap:Hide()
check(not frame:IsShown() and not animation:IsPlaying(), "independent map hide stops preview")
Minimap:Show()
check(frame:IsVisible() and animation:IsPlaying(), "map show restarts enabled preview")
for _, parent in ipairs({ GMM.Ring.Container(), MinimapCluster, UIParent }) do
    parent:Hide()
    check(not frame:IsVisible() and not animation:IsPlaying(), "ancestor hide stops animation")
    parent:Show()
    check(frame:IsVisible() and animation:IsPlaying(), "ancestor show restarts preview")
end
GMM._test.slash("runes off")
check(not frame:IsShown() and not animation:IsPlaying(), "disable stops and hides")
GMM._test.slash("runes status")
check(WoW.chat[#WoW.chat]:find("enabled=false, visible=false, playing=false", 1, true),
    "status reports disabled preview")
Minimap:Hide()
GMM._test.slash("runes on")
check(not frame:IsVisible() and not animation:IsPlaying(), "enable while hidden waits")
Minimap:Show()
check(animation:IsPlaying(), "show honours pending enable")
Minimap:Hide()
GMM._test.slash("runes off")
Minimap:Show()
check(not animation:IsPlaying(), "disable while hidden cancels pending enable")
GMM._test.slash("runes on")
for _, theme in ipairs({ "smoked", "class" }) do
    local before = animation._plays
    GMM.Settings.SetTheme(theme)
    check(frame:IsShown() and animation:IsPlaying(), "theme change keeps preview active")
    check(GMM.Settings.PreviewRunes(true), "all themes allow preview")
    eq(animation._plays, before, "theme change preserves animation phase")
    GMM.Settings.SetTheme("clear")
    check(animation:IsPlaying(), "returning to clear keeps preview active")
    GMM._test.slash("runes on")
end
eq(GMM.db.runicMode, true, "enabled state is saved")
eq(next(GMM.failures), nil, "no runtime failures")

-- Appearance and motion are independent; both layers share native animation
-- clocks with their own halos, and every active clock obeys visibility.
local count = #WoW.animGroups
for _, style in ipairs({ "glowing", "etched" }) do
    GMM._test.slash("runes style " .. style)
    eq(bloom:IsShown(), style == "glowing", "wide blue bloom follows style")
    for _, motion in ipairs({ "orbit", "sway" }) do
        GMM._test.slash("runes motion " .. motion)
        for i, layer in ipairs(layers) do
            eq(layer.core._blendMode, style == "glowing" and "ADD" or "BLEND", "core blending follows style")
            eq(layer.glow:IsShown(), style == "glowing", "halo follows style")
            eq(layer.glow._blendMode, "ADD", "halo adds light")
            eq(layer.rotation:GetTarget(), layer.frame, "core and glow rotate as one frame")
            eq(layer.animation._looping, "REPEAT", "repeat a complete cycle")
            eq(layer.rotation._degrees, motion == "orbit" and (i == 1 and 360 or -360) or 4, "counter rotation or sway")
            eq(layer.rotation._duration, motion == "orbit" and (i == 1 and 30 or 60) or 2, "motion selects duration")
            eq(layer.rotation._smoothing, motion == "orbit" and "NONE" or "IN_OUT", "orbit has constant speed")
            eq(layer.returnRotation._order, 2, "return follows outward motion")
            eq(layer.returnRotation._degrees, motion == "orbit" and 0 or -4, "sway returns to origin")
            eq(layer.returnRotation._duration, motion == "orbit" and 0 or 2, "return takes two seconds without pausing orbit")
            eq(layer.returnRotation._smoothing, motion == "orbit" and "NONE" or "IN_OUT", "return eases at both endpoints")
            eq(layer.animation:IsPlaying(), i == 1 or motion == "orbit", "only active layers play")
            eq(layer.frame:GetFrameLevel(), frame:GetFrameLevel(), "layers stay beneath controls")
        end
        local before = animation._plays
        GMM._test.slash("runes motion " .. motion)
        GMM._test.slash("runes style " .. style)
        eq(animation._plays, before, "repeating choices preserves phase")
        MinimapCluster:Hide()
        for _, layer in ipairs(layers) do check(not layer.animation:IsPlaying(), "hidden layers stop") end
        MinimapCluster:Show()
    end
end
eq(#WoW.animGroups, count, "switching choices reuses animations")
check(not GMM.Settings.SetRunePreviewOption("style", "invalid"), "reject unknown style")
check(not GMM.Settings.SetRunePreviewOption("motion", "invalid"), "reject unknown motion")
GMM._test.slash("runes motion orbit")
GMM._test.slash("runes style glowing")
GMM._test.slash("runes off")
for _, layer in ipairs(layers) do check(not layer.animation:IsPlaying(), "off stops every layer") end
GMM._test.slash("runes on")
GMM.Settings.SetTheme("smoked")
for _, layer in ipairs(layers) do check(layer.animation:IsPlaying(), "theme change preserves orbit layers") end
GMM.Settings.SetTheme("clear")
eq(GMM.db.runeMotion, "orbit", "motion choice is saved")
local fog, fogAnimation = GMM.Ring._test.fog()
local light, mist = bloom:GetRegions(), fog:GetRegions()
for _, theme in ipairs({ "clear", "smoked", "class" }) do
    GMM.Settings.SetTheme(theme)
    local brightness = theme == "smoked" and 0.65 or 1
    local c = theme == "class" and { 0.25, 0.78, 0.92 } or { 1, 1, 1 }
    for channel = 1, 3 do
        near(light._vertex[channel], c[channel], "bloom follows theme hue")
        near(layers[1].glow._vertex[channel], c[channel], "glyph halo follows theme hue")
        near(layers[1].core._vertex[channel], 0.35 + 0.65 * c[channel], "glyph centre is a lighter theme colour")
        near(mist._vertex[channel], 0.5 + 0.5 * c[channel], "vapor follows theme hue softly")
    end
    near(light._vertex[4], 0.7 * brightness, "smoked softens bloom")
end
local classColor = C_ClassColor.GetClassColor
C_ClassColor.GetClassColor = function() return nil end
GMM.Theme.Refresh()
eq(light._vertex[1], 1, "unreadable class colour falls back to white")
C_ClassColor.GetClassColor = classColor
WoW.fire("PLAYER_ENTERING_WORLD", false, false)
near(light._vertex[1], 0.25, "class colour recovery repaints bloom")
GMM.Settings.SetTheme("clear")
GMM._test.slash("runes off")
check(not fog:IsVisible() and not fogAnimation:IsPlaying(), "default vapor stays inactive while mode is off")
GMM._test.slash("runes fog on")
check(not fogAnimation:IsPlaying(), "fog waits while preview is off")
GMM._test.slash("runes on")
check(fog:IsVisible() and fogAnimation:IsPlaying(), "fog enabled with preview")
eq(fog:GetFrameLevel(), Minimap:GetFrameLevel() + 2, "fog behind rune strokes")
local corner, anchor, relative, x, y = fog:GetPoint(1)
eq(corner, "TOPLEFT", "fog expands from top left")
eq(anchor, frame, "vapor follows ring")
