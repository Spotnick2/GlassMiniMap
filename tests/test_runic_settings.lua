-- Shipping settings: owner-selected defaults, conditional controls and persistence.
dofile("tests/wow_stubs.lua")
dofile("tests/harness.lua")
WoW.version = "v0.1.0"
local GMM = loadAddon()
local panel = GMM.Options._test.panel
panel:Show()
local ui = GMM.Options._test.runic
check(not GMM.db.runicMode and not ui.enable:GetChecked(), "runic mode defaults off")
check(not ui.controls:IsShown(), "controls hidden until enabled")
eq(GMM.db.runeStyle, "glowing", "default glowing")
eq(GMM.db.runeMotion, "sway", "default sway")
eq(GMM.db.runeFog, true, "default vapor on")
eq(GMM.db.runeIntensity, 100, "default intensity")
eq(GMM.db.runeSpeed, 100, "default orbit speed")
eq(next(GlassMiniMapDB), nil, "defaults are not written to saved variables")
ui.enable:SetChecked(true); ui.enable:Click("LeftButton")
check(GMM.db.runicMode and ui.controls:IsVisible(), "enable reveals settings")
local frame, animation = GMM.Ring._test.runes()
check(frame:IsVisible() and animation:IsPlaying(), "enable starts runic effects")
check(ui.style[2]:GetChecked(), "selected default style")
check(ui.motion[1]:GetChecked(), "selected default motion")
check(ui.vapor:GetChecked(), "selected default vapor")
ui.style[1]:Click("LeftButton")
ui.motion[2]:Click("LeftButton")
ui.vapor:SetChecked(false); ui.vapor:Click("LeftButton")
WoW.dragSlider(GMM.Options._test.intensity, 35)
WoW.dragSlider(GMM.Options._test.speed, 150)
GMM.Settings.SetTheme("smoked")
local saved = GlassMiniMapDB
GMM = loadAddon({ db = saved })
frame, animation = GMM.Ring._test.runes()
check(frame:IsVisible() and animation:IsPlaying(), "enabled mode survives reload")
eq(GMM.db.runeStyle, "etched", "style survives reload")
eq(GMM.db.runeMotion, "orbit", "motion survives reload")
eq(GMM.db.runeFog, false, "vapor survives reload")
eq(GMM.db.runeIntensity, 35, "intensity survives reload")
eq(GMM.db.runeSpeed, 150, "speed survives reload")
eq(GMM.Theme.Name(), "smoked", "theme survives reload")
panel = GMM.Options._test.panel; panel:Show()
ui = GMM.Options._test.runic
check(ui.motion[2]:GetChecked(), "settings show saved choices")
ui.enable:SetChecked(false); ui.enable:Click("LeftButton")
check(not frame:IsVisible() and not animation:IsPlaying(), "disable stops runes")
check(not ui.controls:IsShown(), "disable hides settings")
eq(GMM.db.runeStyle, "etched", "disable retains choices")
GMM._test.slash("runes on")
check(ui.controls:IsShown() and ui.enable:GetChecked(), "command refreshes settings")
eq(GMM.db.runeMotion, "orbit", "reenable retains choices")
GMM._test.slash("runes off")
GMM = loadAddon({ db = GlassMiniMapDB })
check(not GMM.db.runicMode, "disabled mode survives reload")
GMM = loadAddon({ db = { runicMode = "bad", runeStyle = "bad", runeMotion = {}, runeFog = 1 } })
eq(GMM.db.runicMode, false, "invalid mode repaired")
eq(GMM.db.runeStyle, "glowing", "invalid style repaired")
eq(GMM.db.runeMotion, "sway", "invalid motion repaired")
eq(GMM.db.runeFog, true, "invalid vapor repaired")
eq(next(GMM.failures), nil, "no runic settings failures")
done("test_runic_settings")
